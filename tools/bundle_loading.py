"""Embed the shared helper so existing/cached pages need no new script request.

Run after editing src/loading.js: python tools/bundle_loading.py
"""
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
START = '/* BEGIN shared loading helper (generated by tools/bundle_loading.py) */\n'
END = '/* END shared loading helper */\n'


def bundle():
    helper = (ROOT / 'src/loading.js').read_text(encoding='utf-8').rstrip() + '\n'
    for name in ('workspace.js', 'compare.js'):
        path = ROOT / 'src' / name
        source = path.read_text(encoding='utf-8')
        if START in source:
            prefix, generated = source.split(START, 1)
            source = prefix + generated.split(END, 1)[1]
        directive = "'use strict';\n" if source.startswith("'use strict';\n") else ''
        source = source[len(directive):]
        path.write_text(directive + START + helper + END + source, encoding='utf-8')


if __name__ == '__main__':
    bundle()
